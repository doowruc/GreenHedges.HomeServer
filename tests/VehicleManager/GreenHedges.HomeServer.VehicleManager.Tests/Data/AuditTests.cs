using Microsoft.EntityFrameworkCore;
using GreenHedges.HomeServer.Common.Web.Data;
using GreenHedges.HomeServer.VehicleManager.Tests.Infrastructure;

namespace GreenHedges.HomeServer.VehicleManager.Tests.Data;

public class AuditTests : DatabaseTest
{
    [DatabaseFact]
    public async Task New_rows_are_stamped_with_who_and_when()
    {
        var before = DateTime.UtcNow.AddSeconds(-5);
        await using var db = Db();
        var vehicle = await TestData.AddVehicleAsync(db);
        var entry = await TestData.AddFillUpAsync(db, vehicle.Id, new DateOnly(2026, 1, 1), ("Shell", "Meadowbank"));

        AuditedEntity[] rows = [vehicle, vehicle.Owner!, entry, entry.Stops[0], entry.Stops[0].FuelStation!, entry.Stops[0].FuelStation!.FuelBrand!];
        Assert.All(rows, r =>
        {
            Assert.Equal(UserId, r.AddedBy);
            Assert.Equal(UserId, r.ModifiedBy);
            Assert.True(r.AddedDate >= before);
            Assert.Equal(r.AddedDate, r.ModifiedDate);
            Assert.Equal(8, r.RowVersion.Length);   // generated by SQL Server
        });
    }

    [DatabaseFact]
    public async Task Edits_update_modified_and_rowversion_but_never_added()
    {
        int id;
        byte[] version;
        DateTime added;
        await using (var db = Db())
        {
            var vehicle = await TestData.AddVehicleAsync(db);
            (id, version, added) = (vehicle.Id, vehicle.RowVersion, vehicle.AddedDate);
        }
        await using (var db = Db())
        {
            var vehicle = await db.Vehicles.SingleAsync(v => v.Id == id);
            vehicle.Model = "Changed";
            vehicle.AddedBy = "someone else";
            vehicle.AddedDate = DateTime.UtcNow.AddYears(-10);
            await db.SaveChangesAsync();
        }
        await using (var db = Db())
        {
            var vehicle = await db.Vehicles.AsNoTracking().SingleAsync(v => v.Id == id);
            Assert.Equal("Changed", vehicle.Model);
            Assert.Equal(UserId, vehicle.AddedBy);
            Assert.Equal(added, vehicle.AddedDate);
            Assert.True(vehicle.ModifiedDate > added);
            Assert.NotEqual(version, vehicle.RowVersion);
        }
    }

    [DatabaseFact]
    public async Task A_stale_edit_is_rejected_and_reloaded()
    {
        int id;
        byte[] loaded;
        await using (var db = Db())
        {
            var vehicle = await TestData.AddVehicleAsync(db);
            (id, loaded) = (vehicle.Id, vehicle.RowVersion);
        }
        await using (var first = Db())
        {
            var vehicle = await first.Vehicles.SingleAsync(v => v.Id == id);
            vehicle.Model = "First";
            Assert.True(await first.TrySaveEditAsync(vehicle, loaded));
        }
        await using (var second = Db())
        {
            var vehicle = await second.Vehicles.SingleAsync(v => v.Id == id);
            vehicle.Model = "Second";
            Assert.False(await second.TrySaveEditAsync(vehicle, loaded));
            Assert.Equal("First", vehicle.Model);   // reloaded with the latest values

            vehicle.Model = "Second";
            Assert.True(await second.TrySaveEditAsync(vehicle, vehicle.RowVersion));   // saving again overwrites
        }
    }

    [DatabaseFact]
    public async Task Editing_a_deleted_row_is_rejected()
    {
        await using var db = Db();
        var vehicle = await TestData.AddVehicleAsync(db);
        await using (var other = Db()) await other.Vehicles.Where(v => v.Id == vehicle.Id).ExecuteDeleteAsync();

        vehicle.Model = "Gone";
        Assert.False(await db.TrySaveEditAsync(vehicle, vehicle.RowVersion));
        Assert.Equal(EntityState.Detached, db.Entry(vehicle).State);
    }
}
